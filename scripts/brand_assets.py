#!/usr/bin/env python3
"""Derive the viewer's logo files from docs/brand/NOVIUM_Spatial_Explorer.svg.

  web/public/novium-mark.svg                emblem only (browser tab icon, header)
  web/src/brand.ts                          NOVIUM letter outlines for the header
  crates/xenium-server/src/novium-logo.svg  full logo for the sign-in page

The white background and editor ids are dropped. In the full logo the NOVIUM letters
get class "ink" and "Spatial Explorer" class "ink-text", so a page can recolour them for
a dark theme; the subtitle gets a fixed textLength so a substitute for Century Gothic
keeps the layout. Rerun after replacing the source file:  python3 scripts/brand_assets.py
"""
import copy
import json
import pathlib
import xml.etree.ElementTree as ET

NS = "http://www.w3.org/2000/svg"
ET.register_namespace("", NS)
ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = "docs/brand/NOVIUM_Spatial_Explorer.svg"
EMBLEM = ["01_Orbital_Chain", "02_Back_Ribbon", "03_Main_Gradient_Ribbon",
          "04_Deep_Blue_Fold", "05_Lower_Ribbon", "06_Outer_Cyan_Ribbon"]
EMBLEM_DEFS = ["orbit", "outer", "back", "front", "lower", "edge"] + [f"node{i}" for i in range(1, 7)]
WORDMARK = "07_NOVIUM_Clean_Geometric_Wordmark"
SUBTITLE = "08_Spatial_Explorer_Clean_Typography"
FONT = "'Century Gothic','URW Gothic','TeX Gyre Adventor','Avant Garde',Futura,'Trebuchet MS',sans-serif"


def q(tag):
    return f"{{{NS}}}{tag}"


def local(e):
    return e.tag.rsplit("}", 1)[-1]


src = ET.parse(ROOT / SOURCE).getroot()
defs = {d.get("id"): d for d in src.find(q("defs"))}
groups = {g.get("id"): g for g in src.findall(q("g"))}


def svg(view_box, def_ids, parts, label):
    root = ET.Element(q("svg"), {"viewBox": view_box, "role": "img", "aria-label": label})
    ET.SubElement(root, q("title")).text = label
    d = ET.SubElement(root, q("defs"))
    for i in def_ids:
        d.append(copy.deepcopy(defs[i]))
    for p in parts:
        p = copy.deepcopy(p)
        for e in p.iter():
            e.attrib.pop("id", None)
            e.attrib.pop("data-name", None)
        root.append(p)
    return root


def write(rel, text):
    (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
    (ROOT / rel).write_text(text)
    print("wrote", rel)


def rect_path(e):
    x, y, w, h = (float(e.get(k)) for k in ("x", "y", "width", "height"))
    r = float(e.get("rx", 0))
    return (f"M{x + r:g} {y:g} H{x + w - r:g} A{r:g} {r:g} 0 0 1 {x + w:g} {y + r:g} "
            f"V{y + h - r:g} A{r:g} {r:g} 0 0 1 {x + w - r:g} {y + h:g} H{x + r:g} "
            f"A{r:g} {r:g} 0 0 1 {x:g} {y + h - r:g} V{y + r:g} A{r:g} {r:g} 0 0 1 {x + r:g} {y:g} Z")


# Emblem: square crop around the ribbons and the orbital chain (x 80-581, y 78-647).
mark = svg("40 72 581 581", EMBLEM_DEFS, [groups[g] for g in EMBLEM], "NOVIUM")
write("web/public/novium-mark.svg", ET.tostring(mark, encoding="unicode") + "\n")

# Full logo for the sign-in page.
word = copy.deepcopy(groups[WORDMARK])
word.set("class", "ink")
sub = copy.deepcopy(groups[SUBTITLE])
text = sub.find(q("text"))
text.attrib.pop("transform", None)
text.attrib.update({"x": "1102", "y": "581", "textLength": "968", "lengthAdjust": "spacingAndGlyphs",
                    "font-family": FONT, "class": "ink-text"})
full = svg("70 68 2017 589", EMBLEM_DEFS + ["wordmark"], [groups[g] for g in EMBLEM] + [word, sub],
           "NOVIUM Spatial Explorer")
write("crates/xenium-server/src/novium-logo.svg", ET.tostring(full, encoding="unicode") + "\n")

# Header wordmark: the letter outlines only; the page colours them.
letters = []
for e in groups[WORDMARK]:
    if local(e) == "path":
        letters.append({"d": e.get("d"), "evenodd": e.get("fill-rule") == "evenodd"})
    elif local(e) == "rect":
        letters.append({"d": rect_path(e), "evenodd": False})
write("web/src/brand.ts",
      f"// Generated by scripts/brand_assets.py from {SOURCE}; do not edit.\n"
      "/** Outlines of the NOVIUM letters, in logo coordinates. */\n"
      "export const WORDMARK: { viewBox: string; letters: { d: string; evenodd: boolean }[] } = "
      + json.dumps({"viewBox": "611 204 1468 267", "letters": letters}, indent=2) + ";\n")
